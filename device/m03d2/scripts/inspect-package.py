#!/usr/bin/env python3
"""Strictly inspect the SDK-generated M0.3d.2 package without device access."""

from __future__ import annotations

import hashlib
import json
import pathlib
import sys
import zipfile
from typing import NoReturn

FIRMWARE_SHA256 = "44507c7a7d3029c411b2e3780ea286ca3e08b7e3ffd7b5047d52f73bf5299d1f"
SALT = b"f7bed1c9-7e90-4731-9194-c996666b4331"
ROOT = "autorun/"
NAME = "neurogenic-m03d2-native"
SO = ROOT + NAME + ".so"
EXPECTED = {ROOT + "autorun.check", ROOT + "autorun.json", ROOT + "autorun.sh", SO}


def fail(message: str) -> NoReturn:
    raise SystemExit(f"inspection failed: {message}")


def inspect(package: pathlib.Path, expected_so: pathlib.Path) -> None:
    if not package.is_file() or not expected_so.is_file():
        fail("package or mod library is missing")
    with zipfile.ZipFile(package) as archive:
        infos = archive.infolist()
        files = [info for info in infos if not info.is_dir()]
        names = {info.filename for info in files}
        if names != EXPECTED or len(names) != len(files):
            fail(f"unexpected or duplicate inventory: {sorted(names)}")
        if any((info.external_attr >> 16) & 0o170000 == 0o120000 for info in infos):
            fail("symlink entry")
        manifest = archive.read(ROOT + "autorun.json")
        script = archive.read(ROOT + "autorun.sh")
        check = archive.read(ROOT + "autorun.check")
        library = archive.read(SO)
    if hashlib.sha256(manifest + script + SALT).hexdigest().encode() != check:
        fail("autorun.check mismatch")
    if library != expected_so.read_bytes():
        fail("packaged library differs from inspected library")
    expected_manifest = {
        "value0": {
            "scripts": [{
                "path": "autorun.sh",
                "askQuestion": False,
                "message": "Start NEUROGENIC M0.3d.2 Native?",
                "yesButtonText": "Start",
                "noButtonText": "Cancel",
            }],
            "files": [],
        }
    }
    if json.loads(manifest) != expected_manifest:
        fail("unexpected autorun metadata")
    text = script.decode("utf-8")
    required = (
        "# Generated by mpc-sample-sdk/build-mod.sh.",
        'STOCK="/usr/bin/MPC Sample"',
        f'FW="{FIRMWARE_SHA256}"',
        f'cp "$DIR/{NAME}.so" /run/{NAME}.so || exit 0',
        f"Environment=LD_PRELOAD=/run/{NAME}.so",
        "systemctl daemon-reload",
        "systemctl restart ac50",
    )
    for item in required:
        if text.count(item) != 1:
            fail(f"missing or repeated SDK wrapper operation: {item}")
    prohibited = ("systemd-run", "sshd", "nc -", "curl ", "wget ", "/data/", "/dev/mmc")
    if any(item in text for item in prohibited):
        fail("unexpected service, network, or persistent-storage operation")
    print(f"package_sha256={hashlib.sha256(package.read_bytes()).hexdigest()}")
    print(f"library_sha256={hashlib.sha256(library).hexdigest()}")
    print("inspection=pass")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("usage: inspect-package.py PACKAGE.zip LIBRARY.so")
    inspect(pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]))
